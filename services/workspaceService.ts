import { GeneratedLyric } from '../types';

/**
 * Uploads song lyrics and Suno style prompt to Google Drive as a text file.
 */
export async function uploadToDrive(accessToken: string, lyric: GeneratedLyric): Promise<{ id: string; alternateLink: string }> {
  const filename = `${lyric.title || 'song_lyrics'}_MIX_AI.txt`;
  
  const content = `==================================================
🎵 TITLE: ${lyric.title || 'Untitled Song'}
👤 ARTIST STYLE: ${lyric.input.artist}
🎸 GENRE: ${lyric.input.genre}
⏱️ LENGTH: ${lyric.input.length}
🌍 LANGUAGE: ${lyric.input.language}
==================================================

🎹 SUNO STYLE PROMPT:
${lyric.stylePrompt || 'None'}

🚫 EXCLUDE STYLES (NEGATIVE PROMPT):
${lyric.excludeStyles || 'None'}

🎤 VOCAL GENDER: ${lyric.vocalGender}
🌀 WEIRDNESS: ${lyric.weirdness}%
⚡ STYLE INFLUENCE: ${lyric.styleInfluence}%

==================================================
📝 LYRICS (เนื้อเพลง):
==================================================
${lyric.content}

==================================================
Generated with MIX AI Song Thai Lyricist`;

  const metadata = {
    name: filename,
    mimeType: 'text/plain',
  };

  const boundary = 'mix_ai_song_boundary';
  const delimiter = `\r\n--${boundary}\r\n`;
  const closeDelimiter = `\r\n--${boundary}--`;

  const body =
    delimiter +
    'Content-Type: application/json; charset=UTF-8\r\n\r\n' +
    JSON.stringify(metadata) +
    delimiter +
    'Content-Type: text/plain; charset=UTF-8\r\n\r\n' +
    content +
    closeDelimiter;

  const response = await fetch('https://www.googleapis.com/upload/drive/v3/files?uploadType=multipart&fields=id,webViewLink', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': `multipart/related; boundary=${boundary}`,
    },
    body: body,
  });

  if (!response.ok) {
    const errText = await response.text();
    throw new Error(`Failed to upload to Google Drive: ${errText || response.statusText}`);
  }

  const data = await response.json();
  return {
    id: data.id,
    alternateLink: data.webViewLink,
  };
}

/**
 * Creates a beautiful, formatted Google Doc containing the lyric and metadata.
 */
export async function createGoogleDoc(accessToken: string, lyric: GeneratedLyric): Promise<{ id: string; documentUrl: string }> {
  // Step 1: Create a blank document
  const createResponse = await fetch('https://docs.googleapis.com/v1/documents', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify({
      title: `🎵 ${lyric.title || 'Untitled Song'} - Lyrics & Prompt`,
    }),
  });

  if (!createResponse.ok) {
    const errText = await createResponse.text();
    throw new Error(`Failed to create Google Doc: ${errText || createResponse.statusText}`);
  }

  const doc = await createResponse.json();
  const documentId = doc.documentId;

  // Step 2: Build formatted text
  const title = `🎵 ${lyric.title || 'Untitled Song'}\n`;
  const metaHeader = `Artist: ${lyric.input?.artist || 'Vocalist'} | Genre: ${lyric.input?.genre || 'Pop'} | Length: ${lyric.input?.length || '3-4 min'}\nLanguage: ${lyric.input?.language || 'Thai'}\n\n`;
  const sunoHeader = `🎹 SUNO AI PROMPT DETAILS\n`;
  const sunoPrompt = `• Style Prompt: ${lyric.stylePrompt || 'None'}\n• Exclude Styles: ${lyric.excludeStyles || 'None'}\n• Vocal: ${lyric.vocalGender || 'Not specified'} | Weirdness: ${lyric.weirdness || 40}% | Style Influence: ${lyric.styleInfluence || 60}%\n\n`;
  const lyricHeader = `📝 LYRICS (เนื้อเพลง)\n`;
  const mainLyrics = `${lyric.content || ''}\n\n`;
  const footer = `Generated by MIX AI SONG on ${new Date().toLocaleDateString()}`;

  const fullText = title + metaHeader + sunoHeader + sunoPrompt + lyricHeader + mainLyrics + footer;

  try {
    // Insert all text at index 1
    const requests = [
      {
        insertText: {
          text: fullText,
          location: { index: 1 },
        },
      }
    ];

    await fetch(`https://docs.googleapis.com/v1/documents/${documentId}:batchUpdate`, {
      method: 'POST',
      headers: {
        Authorization: `Bearer ${accessToken}`,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({ requests }),
    });
  } catch (styleErr) {
    console.warn('Google Doc batchUpdate text notice:', styleErr);
  }

  return {
    id: documentId,
    documentUrl: `https://docs.google.com/document/d/${documentId}/edit`,
  };
}

/**
 * Creates a Recording/Composition session event in Google Calendar.
 */
export async function createCalendarEvent(
  accessToken: string,
  lyric: GeneratedLyric,
  dateTimeStr: string, // ISO string or simple YYYY-MM-DDTHH:MM
  durationMinutes: number = 60
): Promise<{ id: string; htmlLink: string }> {
  let startDateTime = new Date(dateTimeStr);
  if (isNaN(startDateTime.getTime())) {
    startDateTime = new Date();
    startDateTime.setDate(startDateTime.getDate() + 1);
    startDateTime.setHours(14, 0, 0, 0);
  }

  const duration = (typeof durationMinutes === 'number' && durationMinutes > 0) ? durationMinutes : 60;
  const endDateTime = new Date(startDateTime.getTime() + duration * 60 * 1000);

  const event = {
    summary: `🎧 MIX AI: บันทึกเพลง "${lyric.title || 'Untitled Song'}"`,
    description: `เซสชันสร้างเพลงและบันทึกดนตรีสำหรับเพลง "${lyric.title || 'Untitled Song'}" ด้วย Suno AI\n\n` +
      `🎸 สไตล์เพลง: ${lyric.stylePrompt || 'Pop'}\n` +
      `🎤 เสียงร้อง: ${lyric.vocalGender || 'Not specified'}\n\n` +
      `เนื้อเพลงบางส่วน:\n${(lyric.content || '').slice(0, 300)}...\n\n` +
      `สร้างและจัดการโดยแอปพลิเคชัน MIX AI SONG`,
    start: {
      dateTime: startDateTime.toISOString(),
      timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone || 'Asia/Bangkok',
    },
    end: {
      dateTime: endDateTime.toISOString(),
      timeZone: Intl.DateTimeFormat().resolvedOptions().timeZone || 'Asia/Bangkok',
    },
    reminders: {
      useDefault: false,
      overrides: [
        { method: 'popup', minutes: 15 },
        { method: 'email', minutes: 60 },
      ],
    },
  };

  const response = await fetch('https://www.googleapis.com/calendar/v3/calendars/primary/events', {
    method: 'POST',
    headers: {
      Authorization: `Bearer ${accessToken}`,
      'Content-Type': 'application/json',
    },
    body: JSON.stringify(event),
  });

  if (!response.ok) {
    const errText = await response.text();
    throw new Error(`Failed to create Calendar Event: ${errText || response.statusText}`);
  }

  const data = await response.json();
  return {
    id: data.id,
    htmlLink: data.htmlLink,
  };
}
